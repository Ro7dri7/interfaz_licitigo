import { expect, test } from '@playwright/test'

test('administrator creates priced products, preserves inactive state and cannot add courses', async ({ page, request }, testInfo) => {
  await page.goto('/catalogo')
  await page.getByRole('button', { name: 'Nuevo producto', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre del producto').fill('ISO 9001 - Certificación Inicial Catálogo E2E')
  await dialog.getByLabel('Precio con IGV incluido').fill('4440.25')
  await dialog.getByLabel('Estado del producto').selectOption('false')
  await expect(dialog.getByLabel('Moneda')).toHaveValue('PEN · Sol peruano')
  await expect(dialog.locator('.quote-estimate')).toContainText('4,440.25')
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('nuevo-producto-mobile.png') })
  await dialog.getByRole('button', { name: 'Guardar producto' }).click()
  await expect(dialog).not.toBeVisible()
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: 'ISO 9001 - Certificación Inicial Catálogo E2E' })).toContainText('Inactivo')
  await page.getByRole('button', { name: 'Nuevo producto', exact: true }).click()
  await dialog.getByLabel('Nombre del producto').fill('ISO 9001 - Certificación Inicial con curso')
  await dialog.getByLabel('Precio con IGV incluido').fill('200')
  await dialog.getByRole('button', { name: 'Guardar producto' }).click()
  await expect(dialog.getByRole('alert')).toContainText('no admite cursos')
  await dialog.getByLabel('Nombre del producto').fill('ISO 14001 - Recertificación Catálogo E2E')
  await dialog.getByRole('button', { name: 'Guardar producto' }).click()
  await expect(dialog).not.toBeVisible()
  const { data } = await (await request.get('/api/crm/state')).json()
  expect(data.products.find((p: { name: string }) => p.name === 'ISO 9001 - Certificación Inicial Catálogo E2E'))
    .toMatchObject({ price: 444025, active: false, currency: 'PEN' })
  expect(data.products.find((p: { name: string }) => p.name === 'ISO 14001 - Recertificación Catálogo E2E'))
    .toMatchObject({ price: 20000, active: true })
  expect(data.products.some((p: { name: string }) => p.name.includes('con curso'))).toBe(false)
})
