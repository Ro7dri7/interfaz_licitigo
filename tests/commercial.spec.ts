import { expect, test } from '@playwright/test'

test('signal, explicit request, quote, activity, task and closure persist together', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Tu día, con foco.' })).toBeVisible()
  const before = await (await request.get('/api/crm/state')).json()
  await page.getByRole('button', { name: 'Nuevo prospecto' }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Empresa *', { exact: true }).fill('Empresa Flujo E2E')
  await dialog.getByLabel('RUC', { exact: true }).fill('20998877665')
  await dialog.getByRole('combobox', { name: 'Origen', exact: true }).selectOption('Lici')
  await dialog.getByLabel('Tipo de entrada').selectOption('signal')
  await dialog.getByLabel('Servicio de interés').fill('ISO 9001')
  await dialog.getByRole('combobox', { name: 'Análisis', exact: true }).selectOption('recommended')
  await dialog.getByLabel('Código de licitación').fill('LP-E2E-001')
  await dialog.getByRole('button', { name: 'Registrar prospecto' }).click()
  await expect(dialog).not.toBeVisible()
  const signal = await (await request.get('/api/crm/state')).json()
  expect(signal.data.deals).toHaveLength(before.data.deals.length)
  await page.getByRole('button', { name: 'Nuevo prospecto' }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Empresa *', { exact: true }).fill('Empresa Flujo E2E')
  await dialog.getByLabel('RUC', { exact: true }).fill('20998877665')
  await dialog.getByRole('combobox', { name: 'Origen', exact: true }).selectOption('WhatsApp')
  await dialog.getByLabel('Tipo de entrada').selectOption('quote')
  await dialog.getByLabel('Servicio de interés').fill('ISO 9001')
  await dialog.getByRole('button', { name: 'Registrar prospecto' }).click()
  await expect(dialog).not.toBeVisible()
  const linked = await (await request.get('/api/crm/state')).json()
  const company = linked.data.companies.find((c: { name: string }) => c.name === 'Empresa Flujo E2E')
  const deal = linked.data.deals.find((d: { companyId: string }) => d.companyId === company.id)
  expect(linked.data.deals).toHaveLength(before.data.deals.length + 1)
  expect(deal.prospectIds).toHaveLength(2)
  await page.goto(`/negocios/${deal.id}`)
  await expect(page.getByText('LP-E2E-001', { exact: true })).toBeVisible()
  await page.getByLabel('Etapa del negocio').selectOption('won')
  await expect(page.getByRole('alert')).toContainText('Prepara una cotización')
  await page.getByRole('button', { name: 'Cotizar', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Cantidad', { exact: true }).fill('2')
  await dialog.getByLabel('Descuento (%)').fill('10')
  await dialog.getByLabel('Válida hasta').fill('2027-12-31')
  await dialog.getByLabel('Condiciones').fill('Alcance de ejemplo, sin envío al cliente.')
  await dialog.getByRole('button', { name: 'Guardar borrador' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.deal-value')).toContainText('5,097.60')
  await page.getByRole('button', { name: 'Actividad', exact: true }).click()
  await page.getByLabel('Detalle *').fill('Necesidad confirmada durante la llamada de prueba.')
  await page.getByRole('dialog').getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.locator('.timeline')).toContainText('Necesidad confirmada durante la llamada de prueba.')
  await page.getByRole('button', { name: 'Tarea', exact: true }).click()
  await page.getByLabel('Tarea *', { exact: true }).fill('Revisar propuesta E2E')
  await page.getByLabel('Fecha y hora').fill('2027-01-20T10:00')
  await page.getByRole('dialog').getByRole('button', { name: 'Guardar', exact: true }).click()
  const task = page.locator('.aside-task').filter({ hasText: 'Revisar propuesta E2E' })
  await task.getByRole('button', { name: 'Marcar completada' }).click()
  await expect(task).not.toBeVisible()
  await page.getByLabel('Etapa del negocio').selectOption('won')
  await expect(page.getByLabel('Etapa del negocio')).toHaveValue('won')
  await page.reload()
  await expect(page.getByLabel('Etapa del negocio')).toHaveValue('won')
  await expect(page.locator('.timeline')).toContainText('Tarea completada: Revisar propuesta E2E')
  await page.locator('.quote-mini').click()
  await expect(page.getByRole('dialog')).toContainText('Alcance de ejemplo')
  await page.emulateMedia({ media: 'print' })
  await expect(page.locator('.quote-sheet')).toBeVisible()
  await page.emulateMedia({ media: 'screen' })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(errors).toEqual([])
})

test('advisor converts a signal and records loss reason', async ({ page }) => {
  await page.goto('/prospectos?tipo=signal')
  await page.getByRole('button', { name: 'Operaciones Alerce' }).click()
  await page.getByRole('button', { name: 'Confirmar interés y abrir negocio' }).click()
  const row = page.getByRole('row').filter({ hasText: 'Operaciones Alerce' })
  await row.getByRole('link', { name: 'Ver negocio' }).click()
  await page.getByLabel('Etapa del negocio').selectOption('lost')
  await page.getByLabel('Motivo de pérdida').fill('El cliente ya tiene certificación vigente.')
  await page.getByRole('button', { name: 'Marcar como perdido' }).click()
  await page.reload()
  await expect(page.getByLabel('Etapa del negocio')).toHaveValue('lost')
  await expect(page.locator('.properties')).toContainText('certificación vigente')
})

test('mobile navigation and form fit, trap focus and close with Escape', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Abrir navegación' }).click()
  await page.getByRole('link', { name: 'Negocios', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Negocios', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Nueva oportunidad' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  for (let i = 0; i < 23; i++) {
    await page.keyboard.press('Tab')
    expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
  }
  const box = await dialog.boundingBox()
  expect(box!.width).toBeLessThanOrEqual(375)
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Nueva oportunidad' })).toBeFocused()
})

test('empty filters and failed API have a recovery path', async ({ page }) => {
  await page.goto('/contactos?q=NO-EXISTE-1234')
  await expect(page.getByRole('heading', { name: 'No hay resultados' })).toBeVisible()
  await page.route('**/api/crm/state', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Almacenamiento de prueba no disponible.' }) }))
  await page.reload()
  await expect(page.getByRole('heading', { name: 'No pudimos cargar el CRM' })).toBeVisible()
  await page.unroute('**/api/crm/state')
  await page.getByRole('button', { name: 'Reintentar conexión' }).click()
  await expect(page.getByRole('heading', { name: 'Contactos', exact: true })).toBeVisible()
})
